import https from "node:https"
import { createProxyAgent } from "./proxy.mjs"
import { IssuePlatformError } from "./issue-platform.mjs"
import { imageCommentBody, imageHash, RUN_IMAGE_LIMITS } from "./run-images.mjs"

export function isLinearImageUrl(value) {
  try {
    const url = new URL(value)
    return url.protocol === "https:" && url.hostname === "uploads.linear.app" &&
      !url.port && !url.username && !url.password && !url.hash && !url.search &&
      /^\/[A-Za-z0-9_-]+(?:\/[A-Za-z0-9._-]+)+$/u.test(url.pathname)
  } catch { return false }
}

// Authentication stays in the service client closure. Redirects are never followed.
export function readLinearImage(url, apiKey, maxBytes, { request = https.request } = {}) {
  if (!isLinearImageUrl(url) || !Number.isInteger(maxBytes) || maxBytes < 1 || maxBytes > RUN_IMAGE_LIMITS.fileBytes) {
    return Promise.reject(imageReadError("INVALID_REQUEST"))
  }
  return new Promise((resolve, reject) => {
    const req = request(new URL(url), {
      method: "GET",
      headers: { Authorization: apiKey },
      agent: createProxyAgent(new URL(url)),
    }, (response) => {
      const status = response.statusCode
      if (status !== 200) {
        response.resume()
        reject(imageReadError(status === 429 ? "RATE_LIMITED" : status >= 500 ? "UNAVAILABLE" : "CONFLICT", status === 429 || status >= 500))
        return
      }
      let size = 0
      const chunks = []
      response.on("data", (chunk) => {
        size += chunk.length
        if (size > maxBytes) {
          response.destroy()
          reject(imageReadError("CONFLICT"))
          return
        }
        chunks.push(chunk)
      })
      response.on("end", () => resolve(Buffer.concat(chunks)))
      response.on("error", () => reject(imageReadError("UNAVAILABLE", true)))
      response.on("aborted", () => reject(imageReadError("UNAVAILABLE", true)))
    })
    // A total deadline also bounds slow trickle responses.
    const timer = setTimeout(() => req.destroy(imageReadError("UNAVAILABLE", true)), 30000)
    req.on("close", () => clearTimeout(timer))
    req.on("error", () => reject(imageReadError("UNAVAILABLE", true)))
    req.end()
  })
}

export async function verifyLinearCommentImages({ operation, intent, comment, readImage }) {
  const resourceId = intent.commentId
  const conflict = { status: "conflict", resourceId, reason: "评论图片、正文或引用无法核对，需要人工处理。" }
  if (comment?.id !== resourceId || comment.archivedAt || !intent.images?.length) return conflict
  const references = []
  // Only the exact image suffix generated by the service is accepted. No generic
  // Markdown URL extraction or Agent-provided URL is sent to the authenticated client.
  const imagePattern = /!\[(?:\\.|[^\]\\])*\]\(([^\s)]+)\)/gu
  const matches = [...comment.body.matchAll(imagePattern)]
  const images = intent.images
  if (matches.length !== images.length) return conflict
  for (const match of matches) references.push(match[1])
  if (imageCommentBody(operation.payload.body, images, references) !== comment.body) return conflict
  for (const [index, reference] of references.entries()) {
    const expected = images[index]
    let bytes
    if (reference.startsWith(`data:${expected.contentType};base64,`)) {
      const encoded = reference.slice(reference.indexOf(",") + 1)
      if (encoded.length > Math.ceil(expected.size / 3) * 4 || !/^[A-Za-z0-9+/]*={0,2}$/u.test(encoded)) return conflict
      bytes = Buffer.from(encoded, "base64")
    } else {
      if (!isLinearImageUrl(reference) || typeof readImage !== "function") return conflict
      bytes = await readImage(reference, expected.size)
    }
    if (bytes.length !== expected.size || imageHash(bytes) !== expected.sha256) return conflict
  }
  return { status: "verified", resourceId, references }
}

function imageReadError(code, retryable = false) {
  return new IssuePlatformError({ code, operation: "comment.create", path: "$.payload.images", retryable })
}
